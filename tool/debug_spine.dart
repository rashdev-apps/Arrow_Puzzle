import 'dart:math';
import 'package:arrow_puzzle/features/game/logic/difficulty_config.dart';
import 'package:arrow_puzzle/features/game/logic/generator/shapes.dart';
import 'package:arrow_puzzle/features/game/domain/arrow.dart';
import 'package:arrow_puzzle/features/game/domain/board.dart';
import 'package:arrow_puzzle/features/game/domain/grid_cell.dart';
import 'package:arrow_puzzle/features/game/domain/direction.dart';
import 'package:arrow_puzzle/features/game/logic/solver.dart';

void main() {
  final s = kBuiltinShapes.first;
  final (minArrows, maxArrows) = DifficultyConfig.targetArrowCount(1);
  final targetN = (minArrows + maxArrows) / 2.0;
  final targetCells = targetN * 4.3;
  final scale = sqrt(targetCells / s.cells.length);
  final scaled = s.resized((s.baseRows * scale).round(), (s.baseCols * scale).round());
  final rows = scaled.baseRows;
  final cols = scaled.baseCols;
  final mask = scaled.toMask();

  const solver = Solver();

  // Reverse generation with back-tracking / candidate selection:
  // In reverse order:
  // When placing arrow X:
  // X's exit ray MUST NOT intersect any ALREADY-PLACED arrows!
  // BUT does X have to block arrows.last?
  // What if X blocks ANY arrow in the currently-unblocked set?
  // Let U = set of currently unblocked arrows in reverse list.
  // When we start, U = {}.
  // We place R_n. Now U = {R_n}.
  // Next, we place R_{n-1}.
  // If R_{n-1} blocks an arrow in U (say R_n):
  // R_n is removed from U!
  // And R_{n-1} is added to U!
  // So U still has size 1!
  // If we repeat this invariant:
  // Every newly placed arrow MUST block an arrow currently in U!
  // Then |U| NEVER INCREASES!
  // At every step, |U| remains exactly 1!
  // And at the very end when all arrows are placed, |U| is STILL exactly 1!
  // That single arrow in U is R_1, the ONLY arrow with a clear exit ray at level start!
  // And when R_1 is removed, the arrow that it was blocking is now the ONLY arrow in U!
  // So at every single step of the game, exactly ONE arrow is free!
  //
  // Let's verify why this is mathematically guaranteed:
  // 1. Initially, place R_n. U = {R_n}.
  // 2. Next, place R_{n-1}. R_{n-1} blocks R_n. R_{n-1} itself has clear exit ray.
  //    Now R_n is blocked by R_{n-1}. R_{n-1} is unblocked.
  //    So U = {R_{n-1}}. Size is 1!
  // 3. Next, place R_{n-2}. R_{n-2} blocks R_{n-1}. R_{n-2} has clear exit ray.
  //    Now R_{n-1} is blocked by R_{n-2}. R_{n-2} is unblocked.
  //    So U = {R_{n-2}}. Size is 1!
  // 4. In general: when placing R_k, if R_k blocks the single arrow in U, |U| remains 1!
  // What if R_k ALSO blocks other already-placed arrows?
  // Those arrows were already blocked, so blocking them again changes nothing! |U| is still 1!
  //
  // What if we cannot block the current arrow in U?
  // Then we can add R_k without blocking, so |U| becomes 2 (for easy levels).
  //
  // Why did our previous attempt at this stop at 10-13 arrows?
  // Let's find out!
  // Because in our previous attempt, we required R_k to be generated by a random walk from its head,
  // where its head was chosen randomly, and we hoped it would stumble upon U's exit ray!
  // BUT U's exit ray is a SPECIFIC straight line of cells!
  // If U's exit ray has cells C1, C2, C3...
  // Why choose a random head?
  // ANY cell on U's exit ray can be PART OF R_k's BODY!
  // If cell C is on U's exit ray:
  // R_k's path can simply start or pass through C!
  // And R_k's head can point in any direction perpendicular or away from U's arrow!
  // Let's test this directly!
  print('Testing direct ray anchor growth...');
  for (var seed = 0; seed < 10; seed++) {
    final rng = Random(seed);
    final free = <GridCell>{};
    for (var r = 0; r < rows; r++) {
      for (var c = 0; c < cols; c++) {
        if (mask[r * cols + c]) free.add(GridCell(r, c));
      }
    }
    final occupied = <GridCell, String>{};
    final chain = <Arrow>[];

    // Place Rn
    final rn = findArrowWithRayToEdge(free, rows, cols, mask, rng, 'a0');
    if (rn == null) continue;
    chain.add(rn);
    for (final c in rn.path) {
      free.remove(c);
      occupied[c] = rn.id;
    }

    var U = <Arrow>[rn];

    while (chain.length < maxArrows && free.isNotEmpty && U.isNotEmpty) {
      // Pick target from U to block
      final target = U.last;
      final ray = getExitRay(target, rows, cols);
      final rayCells = ray.where((c) => free.contains(c)).toList();
      if (rayCells.isEmpty) {
        // target's exit ray has no free cells (hits edge or blocked)
        U.remove(target);
        continue;
      }

      // Try each cell on ray as an anchor for R_k
      rayCells.shuffle(rng);
      Arrow? placed;

      for (final anchor in rayCells) {
        // Can R_k have its body pass through anchor?
        // Let's test anchor as head, or anchor as body
        // Test directions for anchor as head:
        for (final dir in DirectionX.orthogonal) {
          if (!isRayClear(anchor, dir, occupied, rows, cols)) continue;
          final path = walkBackwards(anchor, dir, 3 + rng.nextInt(3), free, rows, cols, mask, rng);
          if (path.length >= 3) {
            placed = Arrow(id: 'a${chain.length}', path: path, dir: dir);
            break;
          }
        }
        if (placed != null) break;

        // Test anchor as body: start backward walk from a free neighbor of anchor,
        // or walk forward through anchor!
        final dirs = [...DirectionX.orthogonal]..shuffle(rng);
        for (final dir in dirs) {
          // If dir is forward direction: head is anchor + dir
          final head = anchor.shift(dir);
          if (!head.inside(rows, cols) || !mask[head.row * cols + head.col] || !free.contains(head)) continue;
          if (!isRayClear(head, dir, occupied, rows, cols)) continue;
          // Path starts at head, goes to anchor, then continues backward
          final remainingLen = 2 + rng.nextInt(3);
          final pathFromAnchor = walkBackwards(anchor, dir, remainingLen, free.difference({head}), rows, cols, mask, rng);
          if (pathFromAnchor.length >= 2) {
            final fullPath = [head, ...pathFromAnchor];
            placed = Arrow(id: 'a${chain.length}', path: fullPath.reversed.toList(), dir: dir);
            break;
          }
        }
        if (placed != null) break;
      }

      if (placed != null) {
        chain.add(placed);
        for (final c in placed.path) {
          free.remove(c);
          occupied[c] = placed.id;
        }
        // target is now blocked!
        U.remove(target);
        // placed is now unblocked!
        U.add(placed);
      } else {
        // Could not block target
        U.remove(target);
      }
    }

    print('Seed $seed: Chain length = ${chain.length}');
    if (chain.length >= 15) {
      final board = Board(rows: rows, cols: cols, mask: mask, arrows: chain);
      final m = DifficultyConfig.evaluate(board);
      print('  Solvable: ${solver.solvableByGreedy(board)}, maxWave=${m.maxFreeWave}, free0=${m.free0}, avgFree=${m.avgFree}');
    }
  }
}

List<GridCell> getExitRay(Arrow arrow, int rows, int cols) {
  final ray = <GridCell>[];
  var c = arrow.head.shift(arrow.dir);
  while (c.inside(rows, cols)) {
    ray.add(c);
    c = c.shift(arrow.dir);
  }
  return ray;
}

bool isRayClear(GridCell head, Direction dir, Map<GridCell, String> occupied, int rows, int cols) {
  var c = head.shift(dir);
  while (c.inside(rows, cols)) {
    if (occupied.containsKey(c)) return false;
    c = c.shift(dir);
  }
  return true;
}

Arrow? findArrowWithRayToEdge(Set<GridCell> free, int rows, int cols, List<bool> mask, Random rng, String id) {
  final heads = free.toList()..shuffle(rng);
  for (final head in heads) {
    final dirs = [...DirectionX.orthogonal]..shuffle(rng);
    for (final dir in dirs) {
      var c = head.shift(dir);
      var clear = true;
      while (c.inside(rows, cols)) {
        if (!free.contains(c)) {
          clear = false;
          break;
        }
        c = c.shift(dir);
      }
      if (!clear) continue;
      final path = walkBackwards(head, dir, 3 + rng.nextInt(3), free, rows, cols, mask, rng);
      if (path.length >= 3) return Arrow(id: id, path: path, dir: dir);
    }
  }
  return null;
}

List<GridCell> walkBackwards(GridCell head, Direction forwardDir, int targetLen, Set<GridCell> free, int rows, int cols, List<bool> mask, Random rng) {
  final backwardsDir = forwardDir.opposite;
  final path = <GridCell>[head];
  final claimed = <GridCell>{head};
  var current = head;
  var currentBackDir = backwardsDir;
  while (path.length < targetLen) {
    final candidates = [currentBackDir, turnLeft(currentBackDir), turnRight(currentBackDir)]..shuffle(rng);
    GridCell? next;
    Direction? chosenDir;
    for (final d in candidates) {
      final step = current.shift(d);
      if (step.inside(rows, cols) && mask[step.row * cols + step.col] && free.contains(step) && !claimed.contains(step)) {
        next = step;
        chosenDir = d;
        break;
      }
    }
    if (next == null) break;
    path.add(next);
    claimed.add(next);
    current = next;
    currentBackDir = chosenDir!;
  }
  return path.reversed.toList();
}

Direction turnLeft(Direction d) => switch (d) {
  Direction.up => Direction.left,
  Direction.left => Direction.down,
  Direction.down => Direction.right,
  Direction.right => Direction.up,
};

Direction turnRight(Direction d) => switch (d) {
  Direction.up => Direction.right,
  Direction.right => Direction.down,
  Direction.down => Direction.left,
  Direction.left => Direction.up,
};

